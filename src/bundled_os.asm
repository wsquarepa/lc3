; Bundled OS: cycle-optimized TRAP routines for this simulator.
;
; Contract (ADR 0005): GETC, OUT, PUTS, IN, PUTSP and HALT give the same
; program output and R0 as the reference OS and preserve R1-R6; R7 and the
; condition codes are unspecified on return. Devices always read ready, so no
; routine polls a status register. Cycle counts, optimality arguments and the
; layout's word budget are in docs/bundled-os-proof.md.
;
; Placement follows the Patt and Patel 2nd edition memory map (Figure A.1):
; code and data live only in x0200-x2FFF, and the trap vector table
; x0000-x00FF is written by boot. Nothing is placed in the interrupt vector
; table (x0100-x01FF) or the device page (xFE00-xFFFF).
;
; Layout: PUTSP's table occupies eight words at the start of each of 32
; consecutive 256-word rows (x0201-x2108). Every routine except PUTS lives in
; the first two gaps between rows; PUTS, unrolled, fills the contiguous space
; above the table (x2109 up).
;
; Device registers are out of PC-relative reach, so a routine reaches them
; either through a pointer (LDI/STI) or through a base register holding
; xFE0A, from which KBDR is at offset -8 and DDR at -4. The low byte of xFE0A
; is a linefeed, so that base register can also be stored to DDR to print
; '\n'.

	.ORIG x0200
	BRnzp BOOT		; x0200 is the boot entry; the table row starts at x0201

; HIGH_TABLE: row n (n = W[12:8]) starts at HIGH_TABLE + n * x100; entry t
; (t = W[15:13]) holds h = t * x20 + n, which is x0000 only for h = 0.
HIGH_TABLE
	.FILL x00
	.FILL x20
	.FILL x40
	.FILL x60
	.FILL x80
	.FILL xA0
	.FILL xC0
	.FILL xE0

; Boot (uncounted) starts at x0200, which branches here past the first
; table row. It fills the trap vector table with UNKNOWN_TRAP, points the six
; assigned vectors at their routines, and halts. R0 is zero on entry.
BOOT	LD R1,UNKNOWN_TRAP
	LD R2,VECTOR_COUNT
BOOT_FILL
	STR R1,R0,#0
	ADD R0,R0,#1
	ADD R2,R2,#-1
	BRp BOOT_FILL
	LD R0,FIRST_VECTOR
	LEA R1,TRAP_GETC
	STR R1,R0,#0
	LEA R1,TRAP_OUT
	STR R1,R0,#1
	LD R1,PUTS_VECTOR	; TRAP_PUTS is beyond LEA reach of boot
	STR R1,R0,#2
	LEA R1,TRAP_IN
	STR R1,R0,#3
	LEA R1,TRAP_PUTSP
	STR R1,R0,#4
	LD R1,HALT_VECTOR	; TRAP_HALT is beyond LEA reach of boot
	STR R1,R0,#5
	AND R0,R0,#0
	STR R0,R0,#-2		; x0000 - 2 = xFFFE: MCR <- 0 halts boot

; GETC: R0 <- next input byte. LDI is cheaper than building a base register
; for a single device access.
TRAP_GETC
	LDI R0,KBDR_PTR
	RET

; OUT: print R0[7:0]; R0 unchanged.
TRAP_OUT
	STI R0,DDR_PTR
	RET

; IN: R0 <- next input byte, then echo it and a linefeed (the reference
; prompt is omitted). R7 is spilled so that it can hold DDR_NL, which serves
; as the device base for all three accesses and as the linefeed itself.
TRAP_IN
	ST R7,SAVE_R7
	LD R7,DDR_NL
	LDR R0,R7,#-8		; KBDR
	STR R0,R7,#-4		; echo
	STR R7,R7,#-4		; '\n' from the base's low byte
	LD R7,SAVE_R7
	RET


; PUTSP: print each word's low byte, then its high byte, stopping at the first
; NUL byte in either position; R0 restored.
;
; The high byte h cannot reach a register's low byte by arithmetic (carries
; only propagate upward), so it is found by a 3-level branch tree on W[15:13]
; followed by a table lookup on W[12:8]: HIGH_TABLE + (W & x1F00) + W[15:13]
; holds h, with x0000 for h = 0.
;
; Registers: R0 = pointer, R7 = word W, R1 = DDR_NL, R2 = x00FF,
; R3 = x1F00, R4 = HIGH_TABLE, R5 = shifted copy of W or the low-byte test.
; Leaf names give W[15:13]. Leaf 011 (h = x60-x7F, lower-case ASCII) falls
; through into the next word; every other leaf branches back.
TRAP_PUTSP
	ST R7,SAVE_R7
	ST R0,SAVE_R0
	ST R1,SAVE_R1
	ST R2,SAVE_R2
	ST R3,SAVE_R3
	ST R4,SAVE_R4
	ST R5,SAVE_R5
	LD R1,DDR_NL
	LD R2,LOW_MASK
	LD R3,HIGH_MASK
	LD R4,HIGH_TABLE_PTR
	BRnzp PUTSP_WORD
PUTSP_01
	ADD R5,R5,R5		; sign = W[13]
	BRzp PUTSP_010
PUTSP_011
	AND R7,R7,R3
	ADD R7,R7,R4
	LDR R7,R7,#3
	STR R7,R1,#-4
	ADD R0,R0,#1
PUTSP_WORD
	LDR R7,R0,#0		; sign = W[15]
	BRn PUTSP_1
	AND R5,R7,R2
	BRz PUTSP_EXIT		; low byte NUL
	STR R7,R1,#-4
	ADD R5,R7,R7		; sign = W[14]
	BRn PUTSP_01
	ADD R5,R5,R5		; sign = W[13]
	BRn PUTSP_001
PUTSP_000
	AND R7,R7,R3
	ADD R7,R7,R4
	LDR R7,R7,#0
	BRz PUTSP_EXIT		; high byte NUL: only possible when W[15:13] = 0
	STR R7,R1,#-4
	ADD R0,R0,#1
	BRnzp PUTSP_WORD
PUTSP_001
	AND R7,R7,R3
	ADD R7,R7,R4
	LDR R7,R7,#1
	STR R7,R1,#-4
	ADD R0,R0,#1
	BRnzp PUTSP_WORD
PUTSP_010
	AND R7,R7,R3
	ADD R7,R7,R4
	LDR R7,R7,#2
	STR R7,R1,#-4
	ADD R0,R0,#1
	BRnzp PUTSP_WORD
PUTSP_1
	AND R5,R7,R2
	BRz PUTSP_EXIT		; low byte NUL
	STR R7,R1,#-4
	ADD R5,R7,R7		; sign = W[14]
	BRn PUTSP_11
	ADD R5,R5,R5		; sign = W[13]
	BRn PUTSP_101
PUTSP_100
	AND R7,R7,R3
	ADD R7,R7,R4
	LDR R7,R7,#4
	STR R7,R1,#-4
	ADD R0,R0,#1
	BRnzp PUTSP_WORD
PUTSP_101
	AND R7,R7,R3
	ADD R7,R7,R4
	LDR R7,R7,#5
	STR R7,R1,#-4
	ADD R0,R0,#1
	BRnzp PUTSP_WORD
PUTSP_11
	ADD R5,R5,R5		; sign = W[13]
	BRn PUTSP_111
PUTSP_110
	AND R7,R7,R3
	ADD R7,R7,R4
	LDR R7,R7,#6
	STR R7,R1,#-4
	ADD R0,R0,#1
	BRnzp PUTSP_WORD
PUTSP_111
	AND R7,R7,R3
	ADD R7,R7,R4
	LDR R7,R7,#7
	STR R7,R1,#-4
	ADD R0,R0,#1
	BRnzp PUTSP_WORD
PUTSP_EXIT
	LD R5,SAVE_R5
	LD R4,SAVE_R4
	LD R3,SAVE_R3
	LD R2,SAVE_R2
	LD R1,SAVE_R1
	LD R0,SAVE_R0
	LD R7,SAVE_R7
	RET


